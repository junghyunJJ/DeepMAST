"""Local Parquet reader for GWAS Catalog data.

Mirrors the function signatures and return structures of gwas_api.py
but reads from local Parquet files in data/gwas_data/ instead of calling the API.

Expected directory layout (relative to project root):
    data/gwas_data/
        associations.parquet   (main association table)
        traits.parquet         (EFO ID → trait name mapping)

Generated by: skills/gwas-database/scripts/download_gwas_bulk.py
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

import pandas as pd

logger = logging.getLogger(__name__)

# ── Data directory ────────────────────────────────────────────────────
DATA_DIR = Path(__file__).resolve().parents[3] / "data" / "gwas_data"

# ── Module-level caches (loaded once on first use) ────────────────────
_assoc_df: pd.DataFrame | None = None
_traits_df: pd.DataFrame | None = None
_disease_context_cache: dict[str, dict[str, Any]] = {}


# ══════════════════════════════════════════════════════════════════════
# Availability check
# ══════════════════════════════════════════════════════════════════════

def is_available() -> bool:
    """Return True if gwas_data/ has associations and traits parquet files."""
    try:
        assoc_ok = (DATA_DIR / "associations.parquet").is_file()
        traits_ok = (DATA_DIR / "traits.parquet").is_file()
        return assoc_ok and traits_ok
    except Exception:
        return False


# ══════════════════════════════════════════════════════════════════════
# Internal loaders
# ══════════════════════════════════════════════════════════════════════

def _load_associations() -> pd.DataFrame:
    """Load and cache associations parquet."""
    global _assoc_df
    if _assoc_df is not None:
        return _assoc_df
    logger.info("Loading GWAS associations parquet from %s", DATA_DIR / "associations.parquet")
    _assoc_df = pd.read_parquet(DATA_DIR / "associations.parquet")
    # Pre-compute upper-cased genes list for fast gene matching
    # genes_list may be numpy arrays (from parquet) rather than Python lists
    if "genes_list" in _assoc_df.columns:
        _GENE_EXCLUDE = {"NAN", "NR", "N/A", "NA", "INTERGENIC", ""}
        _assoc_df["_genes_upper"] = _assoc_df["genes_list"].apply(
            lambda gs: [str(g).upper() for g in gs if str(g).upper() not in _GENE_EXCLUDE]
            if hasattr(gs, '__iter__') and not isinstance(gs, str) else []
        )
    return _assoc_df


def _load_traits() -> pd.DataFrame:
    """Load and cache traits parquet."""
    global _traits_df
    if _traits_df is not None:
        return _traits_df
    logger.info("Loading GWAS traits parquet from %s", DATA_DIR / "traits.parquet")
    _traits_df = pd.read_parquet(DATA_DIR / "traits.parquet")
    return _traits_df


# ══════════════════════════════════════════════════════════════════════
# Public API — mirrors gwas_api.py signatures
# ══════════════════════════════════════════════════════════════════════

def search_efo_traits(trait_name: str) -> list[dict]:
    """Search for EFO trait terms by name (case-insensitive substring match).

    Args:
        trait_name: Disease or trait name to search (e.g. 'type 2 diabetes mellitus').

    Returns:
        List of matching traits with keys: shortForm, trait, uri.
    """
    tdf = _load_traits()
    needle = trait_name.lower()

    # Exact match first
    exact = tdf[tdf["trait"].str.lower() == needle]
    if len(exact) == 0:
        # Substring match
        exact = tdf[tdf["trait"].str.lower().str.contains(needle, na=False)]

    if len(exact) == 0:
        return [{"error": f"No traits found for '{trait_name}'"}]

    results = []
    for _, row in exact.head(20).iterrows():
        results.append({
            "shortForm": row.get("efoId", ""),
            "trait": row.get("trait", ""),
            "uri": row.get("efoUri", ""),
        })
    return results


def get_trait_associations(
    efo_id: str, p_threshold: float = 5e-8, max_results: int = 500
) -> list[dict]:
    """Get SNP-trait associations for an EFO trait, filtered by p-value.

    Args:
        efo_id: EFO identifier (e.g. 'EFO_0001360').
        p_threshold: Maximum p-value to include (default: genome-wide 5e-8).
        max_results: Maximum number of associations to return.

    Returns:
        List of association dicts matching gwas_api.py format.
    """
    df = _load_associations()
    mask = (df["efoId"] == efo_id) & (df["pvalue"].notna()) & (df["pvalue"] <= p_threshold)
    filtered = df[mask].sort_values("pvalue").head(max_results)

    results = []
    for _, row in filtered.iterrows():
        genes_raw = row.get("genes_list", [])
        if hasattr(genes_raw, "tolist"):
            genes_raw = genes_raw.tolist()
        elif not isinstance(genes_raw, list):
            genes_raw = []
        genes = [g for g in genes_raw if str(g).upper() not in ("NAN", "NR", "N/A", "NA", "")]

        results.append({
            "rsId": row.get("rsId", ""),
            "pvalue": float(row["pvalue"]) if pd.notna(row.get("pvalue")) else None,
            "pvalueMantissa": None,
            "pvalueExponent": None,
            "riskAllele": row.get("riskAllele", ""),
            "orPerCopyNum": float(row["orBeta"]) if pd.notna(row.get("orBeta")) else None,
            "betaNum": None,
            "betaUnit": "",
            "genes": genes,
            "studyId": row.get("studyAccession", ""),
            "trait": row.get("trait", ""),
            "chromosome": (str(row.get("chromosome")) if pd.notna(row.get("chromosome")) and row.get("chromosome") != "" else None),
            "position": int(row["position"]) if pd.notna(row.get("position")) else None,
        })

    return results


def get_gene_associations(gene_name: str) -> list[dict]:
    """Get SNPs and their associations for a gene.

    Filters associations where gene_name appears in reported genes.
    Unlike the API version, this returns trait information directly
    without needing follow-up _links.associations calls.

    Args:
        gene_name: HGNC gene symbol (e.g. 'TCF7L2').

    Returns:
        List of SNP dicts matching gwas_api.py format.
    """
    df = _load_associations()
    gene_upper = gene_name.upper()

    mask = df["_genes_upper"].apply(lambda gs: gene_upper in gs)
    gene_df = df[mask]

    if len(gene_df) == 0:
        return []

    # Group by rsId to aggregate associations per SNP (like the API does)
    results = []
    seen_rs: set[str] = set()

    for rs_id, grp in gene_df.groupby("rsId"):
        if pd.isna(rs_id) or not rs_id:
            continue
        if rs_id in seen_rs:
            continue
        seen_rs.add(rs_id)

        # Build location from first row
        first = grp.iloc[0]
        locations = []
        chrom = first.get("chromosome")
        pos = first.get("position")
        if pd.notna(chrom) and chrom:
            loc_entry: dict[str, Any] = {
                "chromosome": str(chrom),
                "position": int(pos) if pd.notna(pos) else None,
                "region": "",
            }
            locations.append(loc_entry)

        # Build associations list from all rows for this SNP
        associations = []
        for _, arow in grp.iterrows():
            trait_name = arow.get("trait", "") or arow.get("mappedTrait", "")
            associations.append({
                "trait": trait_name,
                "pvalue": float(arow["pvalue"]) if pd.notna(arow.get("pvalue")) else None,
                "riskAllele": arow.get("riskAllele", ""),
            })

        results.append({
            "rsId": str(rs_id),
            "functionalClass": first.get("context", ""),
            "locations": locations,
            "associations": associations,
        })

    return results


def build_disease_context(disease_name: str) -> dict[str, Any]:
    """Build and cache disease-level GWAS context for reuse across genes."""
    cache_key = disease_name.strip().lower()
    cached = _disease_context_cache.get(cache_key)
    if cached is not None:
        return cached

    traits = search_efo_traits(disease_name)
    synonyms = {"cancer": "carcinoma", "carcinoma": "cancer"}
    disease_lower = disease_name.lower()
    for old, new in synonyms.items():
        if old in disease_lower:
            alt = disease_lower.replace(old, new)
            alt_traits = search_efo_traits(alt)
            seen_ids = {t.get("shortForm") for t in traits}
            for trait in alt_traits:
                if trait.get("shortForm") not in seen_ids and "error" not in trait:
                    traits.append(trait)

    traits = traits[:5]
    trait_associations: list[dict[str, Any]] = []
    seen_rsids: set[str] = set()
    for trait in traits:
        if "error" in trait:
            continue
        efo_id = trait.get("shortForm", "")
        if not efo_id:
            continue
        for assoc in get_trait_associations(efo_id, max_results=500):
            rsid = assoc.get("rsId", "")
            if rsid and rsid in seen_rsids:
                continue
            if rsid:
                seen_rsids.add(rsid)
            trait_associations.append(assoc)

    cached = {
        "disease": disease_name,
        "efo_traits": traits,
        "trait_associations": trait_associations,
    }
    _disease_context_cache[cache_key] = cached
    return cached


def query_gene_trait_with_context(
    gene_symbol: str,
    disease: str,
    *,
    disease_context: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Return canonical GWAS payload reusing a cached disease context."""
    context = disease_context or build_disease_context(disease)
    result = {
        "gene_symbol": gene_symbol,
        "disease": disease,
        "executed": False,
        "efo_traits": context.get("efo_traits", []),
        "trait_associations": context.get("trait_associations", []),
        "gene_associations": [],
        "errors": [],
    }
    try:
        result["gene_associations"] = get_gene_associations(gene_symbol)
        trait_assocs = result["trait_associations"]
        gene_assocs = result["gene_associations"]
        gene_upper = gene_symbol.upper()
        gene_in_trait = [
            assoc
            for assoc in trait_assocs
            if gene_upper in [g.upper() for g in assoc.get("genes", [])]
        ]
        trait_rsids = {assoc["rsId"] for assoc in trait_assocs if assoc.get("rsId")}
        gene_snps_in_disease = [
            assoc for assoc in gene_assocs if assoc.get("rsId") in trait_rsids
        ]
        result["disease_specific_hits"] = {
            "gene_in_trait_associations": gene_in_trait,
            "gene_snps_in_disease": gene_snps_in_disease,
            "n_gene_in_trait": len(gene_in_trait),
            "n_gene_snps_in_disease": len(gene_snps_in_disease),
        }
        result["executed"] = True
    except Exception as exc:
        result["errors"].append(f"GWAS query failed: {exc}")
    return result


